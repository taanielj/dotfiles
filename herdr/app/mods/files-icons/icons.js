const DEFAULT = ["", "#6D8086"];

// The glyph and colour for a file name, looked up as nvim-web-devicons does:
// the lowercased name, then what follows each of its dots in turn.
export function fileIcon(name) {
  for (let key = name.toLowerCase(); key; key = key.slice(key.indexOf(".") + 1)) {
    if (ICONS[key]) return ICONS[key];
    if (!key.includes(".")) break;
  }
  return DEFAULT;
}
